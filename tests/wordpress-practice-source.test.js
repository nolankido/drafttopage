test('Practice preserves separate approvals and tests unpublished save, reopen and editing', () => {
  const panel = intro.split('<details id="word-practice">')[1]?.split('</details>')[0];
  assert.ok(panel);
  for (const words of ['private workspace backup', 'before applying anything', 'Approve this export separately',
    'export review box', 'Copy WordPress blocks', 'confirm the copy', 'failed or stale copy', 'separate tab',
    'new empty post', 'separate title', 'empty paragraph in Visual editor', 'Ctrl+V', 'Command+V',
    'save as a draft', 'Do not publish', 'Close the post editor', 'reopen the saved draft',
    'remain editable', 'save again', 'reopen once more', 'unexpected-content warnings']) assert.ok(panel.includes(words), words);
});

test('Expected content and limitations do not manufacture successful WordPress or source-app evidence', () => {
  for (const words of ['A small publishing plan', 'Before publishing', 'clear structure', 'source links',
    'https://example.com/', '1. Review the article.', '2. Preview the destination.',
    'Step | Status', 'Review | Ready', 'Publish | Planned',
    'generated by Draft to Page', 'not captured from a current Microsoft Word session',
    'contains no images, private comments, or tracked changes', 'not an automated WordPress check',
    'does not read your WordPress post or record these results']) assert.ok(intro.includes(words), words);
  assert.doesNotMatch(intro, /WordPress verified|publishing succeeded|compatible with every|checked="checked"/i);
});
